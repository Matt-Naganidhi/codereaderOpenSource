/* ═══════════════════════════════════════════════════
   Code Architect — testgen-generic.js
   Python (pytest) and JS/TS (vitest) test scaffolding from parsed
   entities, plus a dependency-free ZIP builder (store method) for
   downloading generated bundles.
   ═══════════════════════════════════════════════════ */

/* ═══ PYTHON GENERATOR ═══ */

function detectPythonTestTargets() {
  const p = APP.parsed;
  return {
    lang: 'python',
    classes: p.classes.filter(c => c.lang === 'python'),
    functions: p.functions.filter(f => f.lang === 'python'),
    hasDjango: p.classes.some(c => (c.widgetType || '').startsWith('django')),
    hasFlask: p.providers.some(pr => pr.type === 'Route'),
  };
}

function generatePythonTestBundle(t) {
  const out = [];
  const byFile = {};
  for (const c of t.classes) (byFile[c.file] = byFile[c.file] || { classes: [], functions: [] }).classes.push(c);
  for (const f of t.functions) (byFile[f.file] = byFile[f.file] || { classes: [], functions: [] }).functions.push(f);

  out.push({
    path: 'tests/conftest.py', suite: 'harness',
    content: `# GENERATED by Code Architect
import os, sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
`,
  });

  for (const [file, ents] of Object.entries(byFile)) {
    const mod = file.replace(/\.py$/, '').replace(/\//g, '.');
    const base = file.split('/').pop().replace(/\.py$/, '');
    let body = `# GENERATED by Code Architect — scaffolds for ${file}
# Fill in constructor arguments / assertions marked TODO.
import pytest

import ${mod} as mod

`;
    for (const cls of ents.classes.slice(0, 20)) {
      body += `
class Test${cls.name}:
    def test_importable(self):
        assert hasattr(mod, '${cls.name}')
${cls.methods.filter(m => !m.startsWith('_')).slice(0, 8).map(m => `
    def test_${m}(self):
        # TODO: instantiate ${cls.name} and assert ${m}() behavior
        assert callable(getattr(mod.${cls.name}, '${m}', None))
`).join('')}`;
    }
    for (const fn of ents.functions.filter(f => !f.name.startsWith('_')).slice(0, 15)) {
      body += `
def test_${fn.name}_exists():
    assert callable(getattr(mod, '${fn.name}', None))
    # TODO: call ${fn.name}(...) with representative inputs
`;
    }
    out.push({ path: `tests/test_${base}.py`, suite: 'unit', content: body });
  }

  out.push({
    path: 'run_tests.sh', suite: 'harness',
    content: `#!/usr/bin/env bash
# GENERATED by Code Architect
set -e
python -m pytest tests/ -v "$@"
`,
  });
  out.push({
    path: 'TESTING.md', suite: 'harness',
    content: `# Test Suite (generated by Code Architect)

pytest scaffolds for ${Object.keys(byFile).length} modules.
Run: \`pip install pytest && ./run_tests.sh\`
Scaffolds assert importability/callability out of the box; TODOs mark
where to add real behavioral assertions.
`,
  });
  return out;
}

/* ═══ JS/TS GENERATOR ═══ */

function detectJsTestTargets() {
  const p = APP.parsed;
  return {
    lang: 'javascript',
    classes: p.classes.filter(c => c.lang === 'javascript'),
    functions: p.functions.filter(f => f.lang === 'javascript' || !f.lang),
    isReact: p.widgets.some(w => (w.widgetType || '').startsWith('react')),
  };
}

function generateJsTestBundle(t) {
  const out = [];
  const byFile = {};
  for (const c of t.classes) (byFile[c.file] = byFile[c.file] || { classes: [], functions: [] }).classes.push(c);
  for (const f of t.functions) (byFile[f.file] = byFile[f.file] || { classes: [], functions: [] }).functions.push(f);

  for (const [file, ents] of Object.entries(byFile).slice(0, 30)) {
    const base = file.split('/').pop().replace(/\.(jsx?|tsx?|mjs|cjs)$/, '');
    const rel = '../' + file.replace(/\.(jsx?|tsx?|mjs|cjs)$/, '');
    let body = `// GENERATED by Code Architect — scaffolds for ${file}
import { describe, it, expect } from 'vitest';
import * as mod from '${rel}';

`;
    for (const cls of ents.classes.slice(0, 10)) {
      body += `describe('${cls.name}', () => {
  it('is exported', () => {
    expect(mod.${cls.name} ?? globalThis.${cls.name}).toBeDefined();
  });
${cls.methods.slice(0, 6).map(m => `  it.todo('${m}() behaves correctly');`).join('\n')}
});

`;
    }
    for (const fn of ents.functions.slice(0, 10)) {
      body += `describe('${fn.name}()', () => {
  it.todo('returns expected output for representative inputs');
});

`;
    }
    out.push({ path: `tests/${base}.test.js`, suite: 'unit', content: body });
  }

  out.push({
    path: 'vitest.config.js', suite: 'harness',
    content: `// GENERATED by Code Architect
import { defineConfig } from 'vitest/config';
export default defineConfig({ test: { environment: '${t.isReact ? 'jsdom' : 'node'}' } });
`,
  });
  out.push({
    path: 'TESTING.md', suite: 'harness',
    content: `# Test Suite (generated by Code Architect)

vitest scaffolds. Run: \`npm i -D vitest${t.isReact ? ' jsdom' : ''} && npx vitest\`
`,
  });
  return out;
}

/* ═══ ZIP BUILDER (store method, no deps) ═══ */

const _CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function _crc32(bytes) {
  let crc = 0xFFFFFFFF;
  for (let i = 0; i < bytes.length; i++) {
    crc = _CRC_TABLE[(crc ^ bytes[i]) & 0xFF] ^ (crc >>> 8);
  }
  return (crc ^ 0xFFFFFFFF) >>> 0;
}

/** files: [{path, content}] → Blob (application/zip) */
function buildZip(files) {
  const enc = new TextEncoder();
  const chunks = [];
  const central = [];
  let offset = 0;

  const u16 = v => new Uint8Array([v & 0xFF, (v >> 8) & 0xFF]);
  const u32 = v => new Uint8Array([v & 0xFF, (v >> 8) & 0xFF, (v >> 16) & 0xFF, (v >> 24) & 0xFF]);

  for (const f of files) {
    const nameBytes = enc.encode(f.path);
    const data = enc.encode(f.content);
    const crc = _crc32(data);

    // Local file header
    const local = [
      u32(0x04034b50), u16(20), u16(0x0800 /* UTF-8 */), u16(0 /* store */),
      u16(0), u16(0), u32(crc), u32(data.length), u32(data.length),
      u16(nameBytes.length), u16(0),
    ];
    const localLen = 30 + nameBytes.length + data.length;
    chunks.push(...local, nameBytes, data);

    central.push({
      nameBytes, crc, size: data.length, offset,
    });
    offset += localLen;
  }

  const centralStart = offset;
  let centralLen = 0;
  for (const e of central) {
    const rec = [
      u32(0x02014b50), u16(20), u16(20), u16(0x0800), u16(0),
      u16(0), u16(0), u32(e.crc), u32(e.size), u32(e.size),
      u16(e.nameBytes.length), u16(0), u16(0), u16(0), u16(0),
      u32(0), u32(e.offset),
    ];
    chunks.push(...rec, e.nameBytes);
    centralLen += 46 + e.nameBytes.length;
  }
  chunks.push(
    u32(0x06054b50), u16(0), u16(0), u16(central.length), u16(central.length),
    u32(centralLen), u32(centralStart), u16(0),
  );
  return new Blob(chunks, { type: 'application/zip' });
}
